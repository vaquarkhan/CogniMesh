"use strict";

/**
 * Export a CogniMesh DataContract as an Apache Spark Declarative Pipelines (SDP) project.
 * Spec: https://spark.apache.org/docs/latest/declarative-pipelines-programming-guide.html
 *
 * CogniMesh remains the control plane: canvas → contract → VRP gate.
 * SDP is the portable Spark runtime for bronze/silver/gold definitions.
 */

function slug(value, fallback = "pipeline") {
  return String(value || fallback)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "") || fallback;
}

function layerSql(contract, layer, fallback) {
  const sql = contract?.spec?.transform?.sparkSql;
  if (layer === "gold" && sql) return sql.trim();
  const layers = contract?.spec?.transform?.sdp?.layers || {};
  if (layers[layer]?.sql) return String(layers[layer].sql).trim();
  return fallback;
}

function defaultBronze(contract) {
  const src = contract?.spec?.source || {};
  const table = src.connection?.table || src.connection?.topic || "input";
  const db = src.connection?.database || "bronze";
  if (src.type === "kafka" || src.type === "kinesis") {
    return `CREATE OR REFRESH STREAMING TABLE ${db}_${table}_bronze AS\nSELECT * FROM STREAM read_files('s3://landing/${table}/', format => 'json')`;
  }
  return `CREATE OR REFRESH MATERIALIZED VIEW ${db}_${table}_bronze AS\nSELECT * FROM read_files('s3://landing/${table}/', format => 'parquet')`;
}

function defaultSilver(contract) {
  const src = contract?.spec?.source || {};
  const table = src.connection?.table || "input";
  const pk = (src.cdc?.primaryKey || ["id"]).join(", ");
  return `CREATE OR REFRESH MATERIALIZED VIEW silver_${table} AS
SELECT *
FROM bronze_${table}_bronze
WHERE ${pk.split(",")[0].trim()} IS NOT NULL`;
}

function defaultGold(contract) {
  const catalog = contract?.spec?.target?.catalog || {};
  const table = catalog.table || "output";
  const sql = contract?.spec?.transform?.sparkSql;
  if (sql && /^(create|select|merge|with)\b/i.test(sql.trim())) {
    if (/^create\b/i.test(sql.trim())) return sql.trim();
    return `CREATE OR REFRESH MATERIALIZED VIEW ${catalog.database || "gold"}.${table} AS\n${sql.trim()}`;
  }
  return `CREATE OR REFRESH MATERIALIZED VIEW ${catalog.database || "gold"}.${table} AS
SELECT * FROM silver_${contract?.spec?.source?.connection?.table || "input"}`;
}

function pvdmHookNote(contract) {
  const pvdm = contract?.spec?.transform?.pvdm;
  if (!pvdm) {
    return "No PVDM block on this contract. Add identityFields/contentFields so CogniMesh can proof-gate the Iceberg commit after SDP run.";
  }
  return [
    "After `spark-pipelines run` succeeds, CogniMesh PVDM must still verify before catalog consumers see gold:",
    `- identityFields: ${(pvdm.identityFields || []).join(", ") || "(unset)"}`,
    `- contentFields: ${(pvdm.contentFields || []).join(", ") || "(unset)"}`,
    "- Invariant: commit_metadata implies VRP = PASS",
  ].join("\n");
}

function generateSparkDeclarativeProject(contract, options = {}) {
  if (!contract?.metadata?.name) {
    return { status: "error", errors: ["contract.metadata.name is required"] };
  }

  const name = slug(contract.metadata.name);
  const domain = slug(contract.metadata.domain || "default");
  const catalog = contract.spec?.target?.catalog || {};
  const storage =
    options.storage ||
    contract.spec?.transform?.sdp?.storage ||
    `s3://cognimesh-${domain}-sdp-checkpoints/${name}/`;
  const database = catalog.database || `cognimesh_${domain}`;
  const isStream = contract.spec?.execution?.mode === "stream";

  const bronze = layerSql(contract, "bronze", defaultBronze(contract));
  const silver = layerSql(contract, "silver", defaultSilver(contract));
  const gold = layerSql(contract, "gold", defaultGold(contract));

  const yaml = [
    `# Generated by CogniMesh from DataContract ${contract.metadata.name}@${contract.metadata.version || "0.0.0"}`,
    `# Apache Spark Declarative Pipelines (SDP) - spark-pipelines CLI`,
    `name: ${name}`,
    "libraries:",
    "  - glob:",
    "      include: transformations/**",
    `storage: ${storage}`,
    `database: ${database}`,
    ...(catalog.catalog ? [`catalog: ${catalog.catalog}`] : []),
    "configuration:",
    '  spark.sql.shuffle.partitions: "auto"',
    `  cognimesh.contract: "${domain}/${name}"`,
    `  cognimesh.pvdm.enabled: "${contract.spec?.transform?.pvdm ? "true" : "false"}"`,
    "",
  ].join("\n");

  const readme = `# ${name} - Spark Declarative Pipelines

Exported from CogniMesh DataContract \`${domain}/${name}\`.

## Run (Spark 4.1+)

\`\`\`bash
pip install "pyspark[pipelines]"
spark-pipelines dry-run
spark-pipelines run
\`\`\`

Mode: **${isStream ? "streaming-capable (bronze may be STREAMING TABLE)" : "batch materialized views"}**.

## Proof gate

${pvdmHookNote(contract)}

Do not grant consumer Lake Formation / Polaris access on gold until CogniMesh Run History shows VRP PASS.

## Layout

- \`spark-pipeline.yml\` - SDP project spec
- \`transformations/*.sql\` - bronze / silver / gold definitions

Docs: https://spark.apache.org/docs/latest/declarative-pipelines-programming-guide.html
`;

  const files = {
    "spark-pipeline.yml": yaml,
    "transformations/01_bronze.sql": `${bronze.endsWith(";") ? bronze : `${bronze};`}\n`,
    "transformations/02_silver.sql": `${silver.endsWith(";") ? silver : `${silver};`}\n`,
    "transformations/03_gold.sql": `${gold.endsWith(";") ? gold : `${gold};`}\n`,
    "README.md": readme,
  };

  return {
    status: "success",
    format: "spark-declarative-pipelines",
    projectName: name,
    files,
    runHint: "spark-pipelines dry-run && spark-pipelines run",
    pvdmRequired: Boolean(contract.spec?.transform?.pvdm),
  };
}

module.exports = { generateSparkDeclarativeProject, slug };
